#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
================================================================================
ETVP 12.5 — Обратная РГ-эволюция (От CODATA к Планку)
================================================================================
Берём экспериментальное значение 1/α = 137.036 и «прокручиваем» его вверх
через КТП-фильтр (интегрирование ренормгруппы от электрона до Планка).

Цель: показать, что «голое» значение на Планке (≈150-158) выводится из
чистой геометрии E8, а не подгоняется.
================================================================================
"""

import numpy as np
import scipy.integrate as integrate

# =============================================================================
# 0. КОНСТАНТЫ
# =============================================================================
PHI = (1.0 + np.sqrt(5.0)) / 2.0
PI = np.pi
SQRT3 = np.sqrt(3.0)

CODATA_ALPHA_INV = 137.035999084  # Экспериментальное значение на низких энергиях

# =============================================================================
# 1. КЛАСС: ОБРАТНАЯ РГ-ЭВОЛЮЦИЯ (ИК → УФ)
# =============================================================================
class InverseRG:
    """
    Прокручивает 1/α от CODATA (макроскопический мир) вверх к Планку.
    """
    def __init__(self):
        self.M_plank = 1.22e19  # ГэВ
        self.M_e = 0.000511  # ГэВ, масса электрона (нижний порог)

        # Таблица порогов включения частиц (ГэВ)
        self.thresholds = {
            'electron': 0.000511,
            'muon': 0.1056,
            'tau': 1.776,
            'W_Z': 91.18,
            'top': 172.5
        }

    def _beta_em(self, mu):
        """
        Коэффициент бета-функции для КЭД:
        b(mu) = (4/3) * sum(Q_i^2) * N_c
        Возвращает b, которое уже включает вклад активных частиц.
        """
        b = 0.0
        if mu > self.thresholds['electron']:
            b += 4.0 / (3.0 * PI)  # e
        if mu > self.thresholds['muon']:
            b += 4.0 / (3.0 * PI)  # μ
        if mu > self.thresholds['tau']:
            b += 4.0 / (3.0 * PI)  # τ
        if mu > self.thresholds['W_Z']:
            # 3 поколения кварков (u,d,s,c,b,t) с 3 цветами
            # Заряды: u,c,t = +2/3; d,s,b = -1/3
            b += (4.0 / (3.0 * PI)) * 3 * (3 * (2/3)**2 + 3 * (1/3)**2)
        return b

    def evolve_inverse(self, start_energy, target_energy):
        """
        Решает уравнение РГ в обратную сторону:
        d(1/α)/d(ln μ) = - b(μ)
        Интегрируем от start_energy до target_energy (в логарифмическом масштабе).
        """
        if start_energy <= 0 or target_energy <= 0:
            raise ValueError("Энергии должны быть > 0")

        # Определяем функцию integrand в переменной ln_mu
        def integrand(ln_mu):
            mu = np.exp(ln_mu)
            return -self._beta_em(mu)

        ln_start = np.log(start_energy)
        ln_target = np.log(target_energy)

        # Интегрируем вклад виртуальных частиц
        vacuum_polarization, _ = integrate.quad(integrand, ln_start, ln_target)
        return vacuum_polarization

    def run_inverse_to_plank(self, alpha_inv_IR=CODATA_ALPHA_INV):
        """
        Основной метод: берём 1/α на макроуровне (например, при массе электрона)
        и прокручиваем через все пороги до Планка.
        """
        print("=" * 80)
        print("ОБРАТНАЯ РГ-ЭВОЛЮЦИЯ (ИК → УФ)")
        print(f"  Исходное значение (CODATA): 1/α = {alpha_inv_IR:.6f}")
        print(f"  Старт: m_e = {self.M_e} ГэВ")
        print(f"  Финиш: M_Plank = {self.M_plank:.2e} ГэВ")
        print("=" * 80)

        # 1. Интегрируем вклад от электрона до Планка
        delta_alpha_inv = self.evolve_inverse(self.M_e, self.M_plank)

        # 2. Вычисляем «голое» значение на Планке
        alpha_inv_UV = alpha_inv_IR + delta_alpha_inv

        print(f"\nИнтеграл вклада вакуума (от m_e до M_Plank): {delta_alpha_inv:.6f}")
        print(f"\n★ Значение 1/α на Планковском масштабе: {alpha_inv_UV:.6f}")

        # 3. Геометрическая интерпретация этого числа через E8
        print("\n" + "=" * 80)
        print("ГЕОМЕТРИЧЕСКАЯ ИНТЕРПРЕТАЦИЯ (E8)")
        print("=" * 80)

        # Классическое выражение: P * K ≈ 137.036
        P = PI * PHI**4 + PI**2 * PHI - 1.0 / (PHI**3 * PI)
        K = np.sqrt(PI * PHI**3) + SQRT3 / (2**7)

        # Ищем множитель, который превращает P*K в α_inv_UV
        # Это может быть просто уточнённое выражение для УФ-предела
        alpha_inv_UV_geo = P * K * (1.0 + 1.0 / (PHI**8 * PI))  # Пример, требует калибровки

        print(f"  Геометрическое выражение P*K = {P * K:.6f}")
        print(f"  Уточнённое выражение (E8 + Φ + π + √3): {alpha_inv_UV_geo:.6f}")
        print(f"  Отклонение от вычисленного значения: {abs(alpha_inv_UV - alpha_inv_UV_geo):.6f}")

        return alpha_inv_UV, alpha_inv_UV_geo

# =============================================================================
# 2. ЗАПУСК
# =============================================================================
if __name__ == "__main__":
    rg = InverseRG()
    alpha_UV, alpha_UV_geo = rg.run_inverse_to_plank()

    print("\n" + "=" * 80)
    print("ВЫВОД ДЛЯ ФИЗИКОВ")
    print("=" * 80)
    print(f"1. Эксперимент (CODATA): 1/α(макро) = 137.035999084")
    print(f"2. После КТП-эволюции вверх: 1/α(Планк) ≈ {alpha_UV:.6f}")
    print(f"3. Геометрия E8 даёт на Планке ≈ {alpha_UV_geo:.6f}")
    print("4. Если (3) ≈ (2), то 'затравка' имеет геометрическое происхождение.")
    print("=" * 80)
