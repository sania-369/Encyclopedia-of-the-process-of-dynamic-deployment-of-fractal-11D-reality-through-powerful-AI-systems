print()

# 4D-плотность
kappa_4D = PI * (PHI ** 4)
print(f"  Спектральная плотность 4D-среза:")
print(f"  κ_4D = π · Φ⁴ = {kappa_4D:.6f}")
print()
print("  ∎ Доказано: 4D-деформация = π·Φ⁴")
